/** 系统语言 → 界面语言。`zh-*` 一律算中文，其余一律英文。 */
export function resolveLang(preference: Settings['language']): Lang {
  if (preference === 'zh' || preference === 'en') return preference;
  // 测试环境与个别嵌入环境里 navigator 可能不存在、或没有 language
  const tag = typeof navigator === 'undefined' ? '' : (navigator.language ?? '');
  if (!tag) return 'zh';
  return tag.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

/** 并列句的分隔符：中文用全角分号，英文用半角分号加空格 */
export function listSeparator(lang: Lang): string {
  return lang === 'zh' ? '；' : '; ';
}

export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: MessageKey, vars?: Vars): string {
  const template: string = (lang === 'en' ? en : zh)[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = vars[name];
    return value === undefined ? whole : String(value);
  });
}

/**
 * 当前界面语言。
 *
 * 语言和主题一样存在加密的 vault 里，没解锁时读不到 —— 这时按浏览器语言走。
 * 这是刻意的：为了"锁屏也守语言"把偏好写到明文里，等于多泄露一条用户特征。
 */
export function useLang(): Lang {
  return resolveLang(useSettings().language);
}

export type Translate = (key: MessageKey, vars?: Vars) => string;

export function useT(): Translate {
  const lang = useLang();
  return useCallback((key: MessageKey, vars?: Vars) => translate(lang, key, vars), [lang]);
}

